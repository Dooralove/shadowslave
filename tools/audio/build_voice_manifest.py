"""Build the voice-line manifest from dialogue resources and barks.

The manifest is an import table, not gameplay data. It gives the future voice
pipeline stable IDs and a file-count target; it does not create voice audio.

Run from the project root:

    python tools/audio/build_voice_manifest.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DIALOGUE = ROOT / "resources" / "dialogue"
BARKS = ROOT / "data" / "dialogues" / "sunny_barks.json"
OUTPUT = ROOT / "resources" / "audio" / "voice_manifest.json"


def main() -> None:
    lines: list[str] = []
    for path in sorted(DIALOGUE.rglob("*.tres")):
        text = path.read_text(encoding="utf-8", errors="ignore")
        count = len(re.findall(r'SubResource\("Line_', text))
        if count == 0:
            continue
        stem = path.stem
        for index in range(count):
            lines.append(f"{stem}_{index:03d}")

    bark_data = json.loads(BARKS.read_text(encoding="utf-8-sig"))
    barks = [f"bark_{entry['id']}" for entry in bark_data.get("barks", []) if entry.get("id")]

    payload = {
        "version": 1,
        "note": "Import table only. No voice files are generated by this tool.",
        "counts": {"lines": len(lines), "barks": len(barks), "total": len(lines) + len(barks)},
        "lines": lines,
        "barks": barks,
    }
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{OUTPUT.relative_to(ROOT)}: {len(lines)} lines + {len(barks)} barks = {len(lines) + len(barks)}")


if __name__ == "__main__":
    main()
